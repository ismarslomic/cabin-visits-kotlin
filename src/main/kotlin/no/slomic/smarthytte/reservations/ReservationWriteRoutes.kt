private const val RESERVATIONS_PATH = "/api/reservations"
private const val RESERVATION_PATH = "/api/reservations/{id}"
private const val EXAMPLE_VERSION = 3

/** The routes that change reservations: admin and family user only (the caller wraps them in `authorized`). */
fun Route.reservationWriteRoutes(reservationService: ReservationService) {
    post(RESERVATIONS_PATH) {
        val actor = checkNotNull(call.principal<UserPrincipal>()) { "Authenticated route without a user" }
        val create = when (val body = call.receiveJsonBody<ReservationCreate>()) {
            is RequestBody.Ok -> body.value
            else -> return@post call.respondApiBodyError(body)
        }

        call.respondCreateResult(reservationService.create(actor, create))
    }.describeCreateReservation()

    put(RESERVATION_PATH) {
        val actor = checkNotNull(call.principal<UserPrincipal>()) { "Authenticated route without a user" }
        val id = checkNotNull(call.parameters["id"]) { "The route has an id" }
        val update = when (val body = call.receiveJsonBody<ReservationUpdate>()) {
            is RequestBody.Ok -> body.value
            else -> return@put call.respondApiBodyError(body)
        }

        call.respondUpdateResult(reservationService.update(actor, id, update))
    }.describeUpdateReservation()

    delete(RESERVATION_PATH) {
        val actor = checkNotNull(call.principal<UserPrincipal>()) { "Authenticated route without a user" }
        val id = checkNotNull(call.parameters["id"]) { "The route has an id" }
        val version = call.request.queryParameters["version"]?.toShortOrNull()
            ?: return@delete call.respond(
                HttpStatusCode.BadRequest,
                ApiError(ApiError.INVALID_REQUEST, "version must be the number of the version you read"),
            )

        call.respondDeleteResult(reservationService.delete(actor, id, version))
    }.describeDeleteReservation()
}

private const val WRITE_RULES = "Admin and family user. Errors are JSON with a code and a message."

private fun Route.describeCreateReservation() = describe {
    operationId = "createReservation"
    tag("Reservations")
    summary = "Create a reservation"
    description = "$WRITE_RULES The id is generated by the server (32 hex characters). The stay is at least " +
        "one instant long, at most 60 nights (UTC dates) and starts at most 2 years ahead, in the past is allowed. " +
        "It must not overlap another reservation. Needs 1-50 existing guests, each once. A calendar notification is " +
        "queued; it never makes the request fail. A retried request after a lost response answers 409."
    requestBody {
        description = "The reservation to create."
        required = true
        schema = jsonSchema<ReservationCreate>()
    }
    responses {
        HttpStatusCode.Created {
            description = "The created reservation, with its generated id and version. The Location header is " +
                "its URL."
        }
        writeErrorResponses()
    }
}

private fun Route.describeUpdateReservation() = describe {
    operationId = "updateReservation"
    tag("Reservations")
    summary = "Update a reservation"
    parameters {
        path("id") {
            description = "Unique identifier of the reservation. Old reservations can have an id that starts with " +
                "an underscore."
            example = GenericElement("a3f9c2e17b4d4e5f8a1b2c3d4e5f6a7b")
        }
    }
    description = "$WRITE_RULES A full replace: the body must carry the version the client read, startTime, " +
        "endTime and the guests. The checks run in this order: the reservation exists (404), the version (412), the " +
        "rules of the request (400), overlap (409). The range rules (at most 60 nights, start at most 2 years " +
        "ahead) apply when the times change. Changing the times clears check-in, check-out and the linked " +
        "trips in the same transaction and queues a calendar update. They are derived again right after the " +
        "commit, in the same request; if that fails it is only logged and the next startup or background run " +
        "recomputes them. A change of guests only, or no change, queues nothing, and " +
        "no change keeps the version."
    requestBody {
        description = "The new times and guests, with the version the client read."
        required = true
        schema = jsonSchema<ReservationUpdate>().allPropertiesRequired()
    }
    responses {
        HttpStatusCode.OK { description = "The updated reservation, with its new version." }
        HttpStatusCode.NotFound { description = "The reservation does not exist." }
        HttpStatusCode.PreconditionFailed {
            description = "The reservation has changed since the version in the body (VERSION_MISMATCH)."
        }
        writeErrorResponses()
    }
}

private fun Route.describeDeleteReservation() = describe {
    operationId = "deleteReservation"
    tag("Reservations")
    summary = "Delete a reservation"
    parameters {
        path("id") {
            description = "Unique identifier of the reservation. Old reservations can have an id that starts with " +
                "an underscore."
            example = GenericElement("a3f9c2e17b4d4e5f8a1b2c3d4e5f6a7b")
        }
        query("version") {
            description = "The version of the reservation that the client read."
            required = true
            example = GenericElement(EXAMPLE_VERSION)
            schema = JsonSchema(type = JsonType.INTEGER)
        }
    }
    description = "$WRITE_RULES Also deletes the guest links, trip links and check-in/out, and queues the removal " +
        "of the calendar event. Past reservations can be deleted, so statistics change retroactively."
    responses {
        HttpStatusCode.NoContent { description = "The reservation is deleted." }
        HttpStatusCode.BadRequest { description = "version is missing or not a number." }
        HttpStatusCode.NotFound { description = "The reservation does not exist." }
        HttpStatusCode.PreconditionFailed {
            description = "The reservation has changed since the version in the query (VERSION_MISMATCH)."
        }
        HttpStatusCode.Unauthorized { description = "The Cloudflare Access token is missing or invalid." }
        HttpStatusCode.Forbidden { description = "The caller is not an admin or family user, or has no role." }
        HttpStatusCode.ServiceUnavailable {
            description = "The database is busy, too many calendar updates are waiting, or Cloudflare Access is not " +
                "configured for the application."
        }
    }
}

private fun Responses.Builder.writeErrorResponses() {
    HttpStatusCode.BadRequest {
        description = "The body is not valid JSON or a property is missing, or a rule is broken: END_BEFORE_START, " +
            "TOO_LONG, TOO_FAR_AHEAD, NO_GUESTS, TOO_MANY_GUESTS, DUPLICATE_GUEST or UNKNOWN_GUEST."
    }
    HttpStatusCode.Unauthorized { description = "The Cloudflare Access token is missing or invalid." }
    HttpStatusCode.Forbidden { description = "The caller is not an admin or family user, or has no role." }
    HttpStatusCode.Conflict { description = "The times overlap another reservation (OVERLAP)." }
    HttpStatusCode.PayloadTooLarge { description = "The request body is larger than 64 KB." }
    HttpStatusCode.UnsupportedMediaType { description = "The Content-Type is not application/json." }
    HttpStatusCode.ServiceUnavailable {
        description = "The database is busy, too many calendar updates are waiting (TEMPORARILY_UNAVAILABLE), or " +
            "Cloudflare Access is not configured for the application."
    }
}
